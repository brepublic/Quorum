let currentLanguage: Language = detectInitialLanguage();
const listeners = new Set<(language: Language) => void>();

function detectInitialLanguage(): Language {
  try {
    const saved = window.localStorage.getItem(STORAGE_KEY);
    if (saved === 'en' || saved === 'zh-CN') {
      return saved;
    }
  } catch {
    // Storage can be unavailable in privacy-restricted browser contexts.
  }

  return window.navigator.language.toLowerCase().startsWith('zh') ? 'zh-CN' : 'en';
}

export function getLanguage(): Language {
  return currentLanguage;
}

export function setLanguage(language: Language) {
  currentLanguage = language;
  try {
    window.localStorage.setItem(STORAGE_KEY, language);
  } catch {
    // Keep the in-memory preference when local storage is unavailable.
  }
  listeners.forEach(listener => listener(language));
}

export function apiErrorText(error: unknown): string { return formatApiError(error, getLanguage()); }

export function t(key: string, values: Record<string, string | number> = {}): string {
  const template = currentLanguage === 'zh-CN' ? zhCN[key] ?? en[key] ?? key : en[key] ?? key;
  return Object.entries(values).reduce(
    (result, [name, value]) => result.replaceAll(`{${name}}`, String(value)),
    template
  );
}

function subscribeLanguage(listener: () => void): () => void {
  listeners.add(listener);
  return () => {listeners.delete(listener);};
}

/** Re-render consumers without replacing component identity or business connections. */
export function useLanguage(): Language {
  return React.useSyncExternalStore(subscribeLanguage, getLanguage, getLanguage);
}

export function LanguageProvider(props: React.PropsWithChildren) {
  const language = useLanguage();

  const dropdownComponent = Dropdown as typeof Dropdown & {
    defaultProps?: Record<string, unknown>;
  };
  dropdownComponent.defaultProps = {
    ...dropdownComponent.defaultProps,
    additionLabel: t('Add '),
    noResultsMessage: t('No results found.')
  };

  const pagination = Pagination as typeof Pagination & {defaultProps?: Record<string, unknown>};
  const defaults = pagination.defaultProps ?? {};
  pagination.defaultProps = {...defaults, 'aria-label': t('Pagination Navigation'),
    ...Object.fromEntries([['firstItem', 'First item'], ['prevItem', 'Previous item'],
      ['nextItem', 'Next item'], ['lastItem', 'Last item']].map(([key, label]) =>
      [key, {...defaults[key] as object, 'aria-label': t(label)}]))};

  React.useEffect(() => {
    document.documentElement.lang = language;
  }, [language]);

  return <>{props.children}</>;
}

export function LanguageSwitcher() {
  const language = useLanguage();

  return (
    <div className="language-switcher">
      <Icon name="language" aria-hidden="true" />
      <Dropdown
        aria-label={t('Language')}
        compact
        selection
        options={[...LANGUAGE_OPTIONS]}
        value={language}
        onChange={(_, data) => setLanguage(data.value as Language)}
      />
    </div>
  );
}

export function LanguageMenuItem(props: { position?: 'left' | 'right' }) {
  return (
    <Menu.Item position={props.position}>
      <LanguageSwitcher />
    </Menu.Item>
  );
}
